    def get_plotting_params(self, run_name):
        #Start with some default values so that the program doesn't hang if they're not present
        #Probably need to change control flow so that the program gracefully handles missing parameters
        fL = 124.2
        phi0 = 0
        phi1 = 0
        pivot = 0
        offset = 0
        plot_mag = True
        plot_Hz = True
        try:
            fL = self.p.child('Global','Tx freq').value()
            phi0 = self.p.child(run_name,'Processing','phase phi 0').value()
            phi1 = self.p.child(run_name,'Processing','phase phi 1').value()
            pivot = self.p.child(run_name,'Processing','phase pivot').value()
            offset = self.p.child(run_name,'Processing','ppm offset').value()
            plot_mag = self.p.child(run_name,'Processing','plot mag').value()
            plot_Hz = self.p.child('Global','Hz plot').value()
            plot_real = True            # not implemented so always treat as if True
        except Exception as e:
            logger.exception("Problem retrieving plotting parameters")
            #TODO: just threw a self. here so that the box doesn't disapper immediatly, need to refactor
            self.msgBox = QMessageBox()
            self.msgBox.setIcon(QMessageBox.Critical)
            self.msgBox.setWindowTitle("Parameter issue")
            self.msgBox.setText("There was a problem retrieving plotting parameters")
            self.msgBox.setInformativeText(str(e))
            self.msgBox.setStandardButtons(QMessageBox.Ok)
            self.msgBox.show()
        return fL, phi0, phi1, pivot, offset, plot_Hz, plot_mag
 
