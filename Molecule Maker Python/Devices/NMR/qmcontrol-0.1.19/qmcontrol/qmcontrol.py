    # run tab fid plot, always autoscale
    def plot_fid(self):
        marginx = 0.05
        marginy = 0.1
        # only if >1 subplots and fid has data
        if hasattr(self.axes,'shape') and len(self.fid)>0:    
             line, = self.axes[0].lines
             rfid = np.real(self.fid)
             line.set_data(self.times, rfid)                  # set data
             min = self.times.min(); max = self.times.max()   # set limits
             dx = marginx*(max - min)
             self.axes[0].set_xlim([min - dx, max + dx])
             min = rfid.min(); max = rfid.max()
             dy = marginy*(max - min)
             self.axes[0].set_ylim([min - dy, max + dy])

    # run tab spectrum plot
    # responds to plotHz/ppm, plot real/mag, autoscale settings
    # always clear the pivot line
    def plot_spectrum(self, xauto=True, yauto=True):
        marginx = 0.05
        marginy = 0.1
        if len(self.spect) > 0:                   # only if spectrum has data
            run_name = self.current_run_name()     
            fL, phi0, phi1, pivot, offset, plot_Hz, plot_mag = self.get_plotting_params(run_name)
            if plot_mag:
                pspect = np.absolute(self.spect)  # plot mag(spectrum)
            else:
                pspect = np.real(self.spect*np.exp(-1j*2*np.pi*phi0/360)\
                     *np.exp(-1j*2*np.pi*(self.freqs - pivot)*phi1/360)) 
            if not(plot_Hz):
                pfreqs = (self.freqs-offset)/fL   # convert freqs to ppm with offset
            else:
                pfreqs = self.freqs
            if hasattr(self.axes,'shape'):        # if >1 subplots need to use axes[1]
                spect_axes = self.axes[1]
            else: 
                spect_axes = self.axes

            line, pivot_line = spect_axes.lines   # get lines
            line.set_data(pfreqs, pspect)         # set plot data
            pivot_line.set_data([],[])            # clear pivot line
            
            # set limits, x is reversed per NMR convention
            if xauto:
                min = pfreqs.min(); max = pfreqs.max()
                dx = marginx*(max - min) 
                spect_axes.set_xlim([max + dx, min - dx])  # [left limit, right limit]
            if yauto:
                min = pspect.min(); max = pspect.max()
                dy = marginy*(max - min)
                spect_axes.set_ylim([min - dy, max + dy])                  
   
