    def check_trigger(self):
        """Runs every 1sec to see if scan file is present in DIRECTORY"""
        self.TRIGGER_DIRECTORY = r".\..\..\scan_trigger.txt" #Normal Mode
        print("Checking")

        #logger.info(f'trigger timer tic')  # for tests
        if self.run_isrunning:     # do nothing if any run is active
            return
        if not self.p.child('Global','trigger enable').value():  # do nothing if not enabled
            return
        #if not self.trigger_hardware_present:
        #    return
        if not os.path.exists(self.TRIGGER_DIRECTORY):
            return
        else:
            #If file exists in directory, Trigger delay timmer to push start button
            logger.info(f'Hardware trigger detected')
            self.trigger_timer.stop()    # stop trigger timer, will be restarted by run
            #Read Trigger File, []
            with open(self.TRIGGER_DIRECTORY) as file:
                #trigger_info = [scan_type, scan_name, save directory, shim_file]
                self.trigger_info = file.read().splitlines() #Read each line in file as seperate list

       
            trigger_delay = self.p.child('Global','trigger delay').value()
            if (trigger_delay != 0):
                logger.info(f"Trigger delay ({trigger_delay} s)...")
            self.trigger_delay_timer.start(trigger_delay*1000)
            
    def start_run_button_down(self):
        #self.runTabRunsComboBox.setCurrentIndex(0) - use to set shim or pulse
        #RuntabRunsComboBox: 0=shim, 1=scan
        print(self.last_run)
        print(self.trigger_info[0])
        print(f"Trigger Info: {self.trigger_info}")
        if self.trigger_info[0] == "scan":
            self.runTabRunsComboBox.setCurrentText("Pulse Acquire")
        elif self.trigger_info[0] == "shim":
            self.last_run = self.trigger_info[0]
            self.runTabRunsComboBox.setCurrentText("Shim")
        

        self.run_isrunning = True       # must be reset by the run when it finishes
        self.trigger_timer.stop()       # stop trigger timer, will be restarted by run
        #Run Dict is the list of all NPulse aquire runs?
        run_name = self.current_run_name()
        current_text = self.runTabStartButton.text()
                        
        if current_text == 'Start':
            self.run_dict[run_name].start_run(self.trigger_info[1], self.trigger_info[2],self.trigger_info[3])
            #Variables: file_name, save_directory, shim_file
        elif current_text == 'Stop':
            self.run_dict[run_name].finish_run()
        elif current_text == 'Stopping...':
            pass
