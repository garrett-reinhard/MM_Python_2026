    @Slot()
    def on_hwQuery(self, ):
        hw_data = {}
        hw_data["present"] = self.si.is_present
        if hw_data["present"]:
            hw_data['deviceId'] = self.si.GetModelSerial()
            hw_data['serialNumber'] = self.si.HardwareKey()
            hw_data['usbInterface'] = str(self.si.USB_Interface())
            hw_data['usbSpeed'] = str(self.si.USB_Speed())
            hw_data['okProductVersion'] = self.si.OKProductName()
            hw_data['okAPIVersion'] = self.si.API_Version()

        self.hw_info_sig.emit(hw_data)

