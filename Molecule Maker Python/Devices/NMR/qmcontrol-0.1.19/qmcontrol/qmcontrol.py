    # slots, Magnet tab
    def mag_plot(self):
        maxpts = 1200      # 1200 samples = 4 hours
        stats_samples = 25 # number of samples for stats, 25 = 5 min
        
        if not self.si.configured: # no hardware present
            return
        
        if self.run_isrunning:     # block RS485 comms to temp controller when a run is running
            return
        
        T_point, enc_point,_,_ = tc.get_MAP(self.si)  # get aliased temperature
        power_point,_,_ = tc.get_PWR(self.si)
        
        if len(self.mag_T) < maxpts:
            self.mag_T.append(T_point)
        else:
            self.mag_T.pop(0)
            self.mag_T.append(T_point)
            
        if len(self.mag_enclosure) < maxpts:
            self.mag_enclosure.append(enc_point)
        else:
            self.mag_enclosure.pop(0)
            self.mag_enclosure.append(enc_point)
            
        if len(self.mag_power) < maxpts:
            self.mag_power.append(power_point)
        else:
            self.mag_power.pop(0)
            self.mag_power.append(power_point)
            
        mag_time = time.perf_counter()/60
        if len(self.mag_times) < maxpts:
            self.mag_times.append(mag_time)
        else:
            self.mag_times.pop(0)
            self.mag_times.append(mag_time)       
        #print('read magnet :', T_point ,enc_point ,power_point ,mag_time)
            
        self.mag_times_0 = [t - self.mag_times[0] for t in self.mag_times]
        self.magAxes[0].clear()
        self.magAxes[1].clear()
        self.magAxes[2].clear()
        self.magAxes[0].plot(self.mag_times_0, self.mag_T, linewidth=1)
        self.magAxes[1].plot(self.mag_times_0, self.mag_enclosure, linewidth=1)
        self.magAxes[2].plot(self.mag_times_0, self.mag_power, linewidth=1)
        
        # report statistics, will throw error if there are any None points in mag_T
        # will happen if temperature controller board does not respond
        try:
            if len(self.mag_T) > stats_samples:
                aveT = statistics.mean(self.mag_T[-(stats_samples+1):-1])
                sigmaT = statistics.stdev(self.mag_T[-(stats_samples+1):-1])
                msg = f'mean = {aveT:2.6f} C, std. dev. = {sigmaT*1000:0.3f} mC (5 min)'
                self.magAxes[0].text(0.03, 0.80, msg, transform=self.magAxes[0].transAxes, fontsize = 7)
        except:
            logger.error(f"Error computing temperature statistics")

        self.magAxes[0].tick_params(direction ='in', right='True', top='True',labelsize=9)
        self.magAxes[1].tick_params(direction ='in', right='True', top='True',labelsize=9)
        self.magAxes[2].tick_params(direction ='in', right='True', top='True',labelsize=9)
        self.magAxes[0].set_ylabel('magnet (C)')
        self.magAxes[0].yaxis.set_major_formatter(FormatStrFormatter('% 2.6f'))
        self.magAxes[1].set_ylabel('ambient (C)')
        self.magAxes[1].yaxis.set_major_formatter(FormatStrFormatter('% 2.6f'))
        self.magAxes[2].set_xlabel('time (minutes)')
        self.magAxes[2].set_ylabel('heater (W)')
        self.magAxes[2].yaxis.set_major_formatter(FormatStrFormatter('% 2.6f'))
        
        #logger.info('Temperature plot updated')
        self.magTabCanvas.draw()
        
