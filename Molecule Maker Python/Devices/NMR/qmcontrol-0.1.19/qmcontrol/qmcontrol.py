    def runTabHzCheckBox_changed(self, state):
        plot_Hz = bool(state)    # unchkd=0, chkd=2
        self.p.child('Global','Hz plot').setValue(plot_Hz)
        run_name = self.current_run_name()
        fL = self.p.child('Global','Tx freq').value()
        offset = self.p.child(run_name,'Processing','ppm offset').value()
        two_plots = hasattr(self.axes,'shape')    # if >1 subplots
        xlim_new = [0,0]
        
        if two_plots and plot_Hz:          # ppm  --> Hz
            xlim = self.axes[1].get_xlim()
            xlim_new[0] = xlim[0]*fL + offset
            xlim_new[1] = xlim[1]*fL + offset
            self.axes[1].set_xlim(xlim_new)
            self.axes[1].set_xlabel('Frequency (Hz)',fontsize=9)
            
        if not two_plots and plot_Hz:
            xlim = self.axes.get_xlim()
            xlim_new[0] = xlim[0]*fL + offset
            xlim_new[1] = xlim[1]*fL + offset
            self.axes.set_xlim(xlim_new)
            self.axes.set_xlabel('Frequency (Hz)',fontsize=9)
            
        if two_plots and not plot_Hz:      # Hz --> ppm
            xlim = self.axes[1].get_xlim()
            xlim_new[0] = (xlim[0] - offset)/fL       
            xlim_new[1] = (xlim[1] - offset)/fL
            self.axes[1].set_xlim(xlim_new)
            self.axes[1].set_xlabel('Frequency (ppm)',fontsize=9)
            
        if not two_plots and not plot_Hz:
            xlim = self.axes.get_xlim()
            xlim_new[0] = (xlim[0] - offset)/fL       
            xlim_new[1] = (xlim[1] - offset)/fL
            self.axes.set_xlim(xlim_new)
            self.axes.set_xlabel('Frequency (ppm)',fontsize=9)
            
        self.plot_spectrum(xauto=False, yauto=False)
        self.runTabCanvas.draw()

